import pytesseract
import re
from ultralytics import YOLO
import easyocr

# Carga modelos
yolo = YOLO("/content/alpr_train/exp1/weights/best.pt")  # tu modelo
easy_reader = easyocr.Reader(['es'], gpu=False)  # fallback, cambia gpu=True si tienes GPU y easyocr la soporta

# Configuración de Tesseract: OEM 3 (LSTM), PSM 7 (una sola línea), y whitelist de caracteres válidos.
TESS_CONFIG = r'--oem 3 --psm 7 -c tessedit_char_whitelist=ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-'

# Regex patrón de placas mexicanas: 3 letras - 3 dígitos - 1 letra
PLATE_REGEX = re.compile(r'([A-Z]{3})[-\s]?(\d{3})[-\s]?([A-Z])')

# Mapeos de sustituciones comunes (errores típicos)
SUBSTITUTIONS = {
    '°': '-',  # Símbolo grado -> guion
    'º': '-',
    ' ': '',
    '—': '-',
    '–': '-',
    '_': '-',
    '|': 'I',
    '¡': 'I',
    '¿': '?',
    '$': 'S',  # Manualmente se revisa
    ']': '',
    '[': '',
    '¡': 'I'
}

# Heurística para corregir confusiones entre O/0, I/1, Z/2, S/5, B/8
CHAR_CONFUSIONS = {
    '0':'O', 'O':'O',
    '1':'1', 'I':'1', 'L':'1',
    '2':'2', 'Z':'2',
    '5':'5', 'S':'5',
    '8':'8', 'B':'8'
}

def postprocess_text(raw_text):
    """Limpia y normaliza texto OCR bruto."""
    if raw_text is None:
        return ''
    s = raw_text.strip()
    # llevar a mayusculas
    s = s.upper()
    # aplicar sustituciones simples
    for k,v in SUBSTITUTIONS.items():
        s = s.replace(k, v)
    # eliminar caracteres no permitidos (dejamos A-Z, 0-9 y '-')
    s = re.sub(r'[^A-Z0-9-]', '', s)
    return s

def try_fix_by_pattern(txt):
    """Intenta extraer patrón AAA-999-A desde cualquier variante en txt."""
    m = PLATE_REGEX.search(txt)
    if not m:
        return None
    # normalizar con guiones
    groups = m.groups()
    fixed = f"{groups[0]}-{groups[1]}-{groups[2]}"
    return fixed

def ocr_with_tesseract(img):
    """Ejecuta Tesseract sobre imagen (grayscale or binarized)."""
    try:
        txt = pytesseract.image_to_string(img, config=TESS_CONFIG)
    except Exception as e:
        print("Tesseract error:", e)
        txt = ""
    return postprocess_text(txt)

def ocr_with_easyocr(img):
    """Fallback con EasyOCR. Devuelve el texto concatenado."""
    try:
        results = easy_reader.readtext(img)
        # easyocr devuelve lista de (bbox, text, conf)
        if not results:
            return ""
        # ordenar por bbox x para formar secuencia
        results_sorted = sorted(results, key=lambda x: x[0][0][0])
        txt = "".join([r[1] for r in results_sorted])
        return postprocess_text(txt)
    except Exception as e:
        print("EasyOCR error:", e)
        return ""

def preprocess_for_ocr(crop):
    """Preprocesamiento intensivo: escala, CLAHE, blur, sharpen, binarize, morph ops."""
    # Escalar para que la altura sea alrededor de 120-200 px (más detalles)
    h, w = crop.shape[:2]
    target_h = 160
    scale = target_h / float(h) if h>0 else 1.0
    new_w = max(200, int(w * scale))
    crop = cv2.resize(crop, (new_w, target_h), interpolation=cv2.INTER_LINEAR)

    gray = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)
    # CLAHE para mejorar contraste
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8,8))
    gray = clahe.apply(gray)
    # Denoise preserving edges
    gray = cv2.bilateralFilter(gray, d=9, sigmaColor=75, sigmaSpace=75)
    # Unsharp mask (sharpen)
    gaussian = cv2.GaussianBlur(gray, (0,0), sigmaX=3)
    sharp = cv2.addWeighted(gray, 1.5, gaussian, -0.5, 0)
    # Morph close to fill gaps in characters
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (3,3))
    morph = cv2.morphologyEx(sharp, cv2.MORPH_CLOSE, kernel, iterations=1)
    # Adaptive threshold (binarización local)
    thresh = cv2.adaptiveThreshold(morph, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
                                   cv2.THRESH_BINARY, 35, 15)
    # Optional: invert if background is dark
    # if np.mean(thresh) < 127:
    #    thresh = 255 - thresh
    return thresh

def recognize_plate_from_image(image_path, save_crops=False, visualize=False):
    """Pipeline completo: detect -> recortar -> preprocess -> ocr -> postprocess -> validar."""
    img = cv2.imread(image_path)
    if img is None:
        raise FileNotFoundError(image_path)
    results = yolo(image_path, conf=0.35, iou=0.5)  # ajustar conf si detecta de más o de menos
    detections = results[0].boxes
    outputs = []
    for i, box in enumerate(detections):
        x1, y1, x2, y2 = map(int, box.xyxy[0])
        crop = img[y1:y2, x1:x2]
        pre = preprocess_for_ocr(crop)

        # intentar Tesseract
        ttxt = ocr_with_tesseract(pre)
        fixed = try_fix_by_pattern(ttxt)
        method = "tesseract"
        if fixed is None or len(fixed) < 6:
            # si no cumple patron, fallback a easyocr
            eout = ocr_with_easyocr(pre)
            fixed = try_fix_by_pattern(eout) or try_fix_by_pattern(ttxt + eout)
            method = "easyocr" if fixed and fixed==try_fix_by_pattern(eout) else "tesseract+easyocr"
        # Si todavía no encontramos patrón, intentamos heurística simple:
        if fixed is None:
            # aplicar reemplazos adicionales y reintentar
            t2 = ttxt
            for k,v in CHAR_CONFUSIONS.items():
                t2 = t2.replace(k, v)
            t2 = postprocess_text(t2)
            fixed = try_fix_by_pattern(t2)
            if fixed:
                method = "heuristic_fix"

        # fallback final: si nada, devolver la mejor cadena limpia (sin patrón)
        best_guess = fixed if fixed else (ttxt if len(ttxt)>0 else eout)
        if save_crops:
            cv2.imwrite(f"crop_{i}.jpg", crop)
            cv2.imwrite(f"crop_pre_{i}.jpg", pre)
        outputs.append({
            "bbox": (x1,y1,x2,y2),
            "raw_tesseract": ttxt,
            "raw_easyocr": eout if 'eout' in locals() else '',
            "plate": best_guess,
            "method": method
        })
        if visualize:
            print(outputs[-1])
    return outputs

