import re

def limpiar_placa(texto):
    """
    Limpia y valida el texto OCR para dejar solo formato AAA999A (7 caracteres).
    """
    if not texto:
        return ""

    # Pasar a mayúsculas
    texto = texto.upper()

    # Reemplazar caracteres comunes mal detectados
    sustituciones = {
        '°': '-', 'º': '-', '—': '-', '–': '-', '_': '-',
        #'O': '0', 'D': '0',  # a veces confunde O con cero
        #'S': '5', 'B': '8',  # letras que parecen números
        #'|': '1', 'I': '1', 'L': '1',
        '$': 'S',
        ']': '', '[': '', ' ': '', '.': '', ',': ''
    }
    for k, v in sustituciones.items():
        texto = texto.replace(k, v)

    # Eliminar todo lo que no sea letra o número
    texto = re.sub(r'[^A-Z0-9]', '', texto)

    # Buscar patrón de 3 letras seguidas de 3 números y 1 letra
    patron = re.search(r'([A-Z]{3})(\d{3})([A-Z])', texto)
    if patron:
        return "".join(patron.groups())  # AAA999A

    # Si no lo encuentra, truncar a los primeros 7 caracteres válidos
    return texto[:7]

